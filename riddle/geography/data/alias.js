function buildReverseMap(forwardMap) {
    const reverseMap = {};  // 使用普通对象
    for (let [alias, canonical] of Object.entries(forwardMap)) {
        if (!reverseMap[canonical]) {
            reverseMap[canonical] = [];
        }
        reverseMap[canonical].push(alias);
    }
    return reverseMap;
}

